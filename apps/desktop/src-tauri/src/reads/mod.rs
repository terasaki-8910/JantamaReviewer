//! 読み（他家の聴牌と待ち。F23）と、解析のモデル（F24）の、本体の側。
//!
//! 読みの計算は、別のプログラム（解析エンジン `jantama-engine`。AGPL-3.0-or-later）が行う。本体（MIT）は、エンジンを別のプロセスとして呼び、
//! 結果のファイルのパスとモデルのパスと出力先だけでやり取りする。モデルは、アプリにもエンジンにも同梱せず、ユーザーが押したときだけ
//! Hugging Face の決まった版を取る（または、自分で取ったファイルを選ぶ）。
//!
//! - `catalog`: 決まった版（リポジトリ・コミット・ファイル名・SHA-256・大きさ・ライセンス・出どころ）と、置き場（設定のフォルダの `models/`）
//! - `model`: 置き場の操作（いまの状態・選んだファイルを置く・消す）。通信しない
//! - `download`: モデルを取る。通信は、ここだけ（S-2。ホストは配布元と、その配布の置き場だけ）
//! - `pump`: 取る間の読み取りを別の担当に任せて、取り消しと停止にすぐ応える道具
//! - `engine_runner`: エンジンを呼ぶ。本体がエンジンを呼ぶのは、ここだけ（S-5）
//! - `reads_file`: 半荘の `reads.json` が、いま使える写しか（モデルが替わったら作り直す。D-8）
//! - `state`: 動いている処理の管理（同時に 1 つの取り込み・半荘ごとに 1 つの計算）
//! - `commands`: 画面から呼ぶ Tauri のコマンド（検討画面だけ）
//!
//! 読みの写し（`reads.json`）とモデルは、どの端末でも作り直せるので、同期にも書き出しにも入れない。

pub mod catalog;
